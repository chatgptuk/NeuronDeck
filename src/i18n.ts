export const getModelDescription = (model: ModelInfo, language: Language): string =>
  language === "zh" ? modelDescriptionsZh[model.id] ?? model.description : model.description;

export const getCapabilityLabel = (capability: Capability, language: Language): string => {
  if (language === "en") return capability;
  return { reasoning: "推理", vision: "视觉", tools: "工具", coding: "编程" }[capability];
};

export const getLocalizedError = (language: Language, code: string | undefined, fallback: string): string => {
  const messages = translations[language].errors as Record<string, string>;
  return (code && messages[code]) || fallback;
};
